const assert = require('node:assert/strict');
const { getPluginRequest, isProductTask } = require('../src/services/builder/pluginRequests');
const { validateAction, listCapabilities } = require('../src/services/wordpressConnector');
const { formatCompletion } = require('../src/services/builder/completionReport');
assert.equal(getPluginRequest('Install Elementor plugin').slug, 'elementor');
assert.equal(getPluginRequest('activate WooCommerce').slug, 'woocommerce');
assert.equal(getPluginRequest('install plugin slug: contact-form-7').slug, 'contact-form-7');
assert.ok(getPluginRequest('install a plugin').error);
assert.equal(getPluginRequest('please create product Cotton Shirt'), null);
assert.equal(getPluginRequest('add WooCommerce products'), null);
assert.equal(isProductTask('Please upload 4 products'), true);
assert.equal(isProductTask('Please build a business website'), false);
assert.ok(listCapabilities().standard.includes('create_woocommerce_products'));
validateAction({action:'create_woocommerce_product',name:'Shirt',regular_price:'19.99'});
validateAction({action:'create_woocommerce_products',products:[{name:'Shirt',regular_price:'19.99'}]});
assert.throws(() => validateAction({action:'create_woocommerce_product',name:'Shirt'}));
assert.throws(() => validateAction({action:'create_woocommerce_products',products:Array(21).fill({name:'Shirt',regular_price:'1'})}));
assert.match(formatCompletion('', [{action:'create_woocommerce_products',success:true,data:{result:{count:3}}}], {buildIntent:true}), /3 WooCommerce product/);
console.log('Plugin requests, product validation, reporting tests passed');
